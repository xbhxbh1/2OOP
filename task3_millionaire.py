# Кожне питання: [текст, відповідь 1, відповідь 2, відповідь 3, відповідь 4, номер правильної]
questions = [
    ["Які кольори має прапор України?", "жовтий і блакитний", "червоний і зелений", "чорний і жовтий", "зелений і фіолетовий", 1],
    ["У якому місті знаходиться ДТЕУ?", "Вінниця", "Київ", "Львів", "Одеса", 2],
    ["Скільки планет у Сонячній системі?", "7", "8", "9", "10", 2],
    ["Яка річка є найдовшою в Україні?", "Дністер", "Південний Буг", "Дніпро", "Сіверський Донець", 3],
    ["Хто написав збірку віршів «Кобзар»?", "Іван Франко", "Леся Українка", "Григорій Сковорода", "Тарас Шевченко", 4],
]

score = 0
number = 1

for q in questions:
    print("Current User Score:", score)
    print(f"Питання {number}, {q[0]}")
    print()
    print("1.", q[1])
    print("2.", q[2])
    print("3.", q[3])
    print("4.", q[4])
    print()

    answer = int(input("Ваша відповідь (номер): "))

    if answer == q[5]:
        print("Correct answer")
        score = score + 100
    else:
        print("Wrong Answer")
        print("Кінець програми. Ваш рахунок:", score)
        break

    number = number + 1

if score == len(questions) * 100:
    print("Current User Score:", score)
    print("Вітаємо! Ви відповіли на всі питання. Кінець програми.")
